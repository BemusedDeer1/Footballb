def generate_dynamic_question():
    """تولید یک سوال تصادفی با ترکیب داده‌های داینامیک"""
    q_type = random.choice([
        "stadium", "nation", "nickname", "number", 
        "wc_host", "wc_winner", "ucl_winner", "ballon_dor", "facts"
    ])

    if q_type == "stadium":
        team, correct_stadium = random.choice(STADIUMS)
        wrong_candidates = [s[1] for s in STADIUMS if s[1] != correct_stadium]
        opts = random.sample(wrong_candidates, 3) + [correct_stadium]
        random.shuffle(opts)
        return {
            "question": f"ورزشگاه خانگی تیم «{team}» چه نام دارد؟",
            "options": opts,
            "correct_idx": opts.index(correct_stadium)
        }

    elif q_type == "nation":
        player, correct_nation = random.choice(NATIONS)
        wrong_candidates = list({n[1] for n in NATIONS if n[1] != correct_nation})
        opts = random.sample(wrong_candidates, 3) + [correct_nation]
        random.shuffle(opts)
        return {
            "question": f"«{player}» برای کدام تیم ملی به میدان می‌رود؟",
            "options": opts,
            "correct_idx": opts.index(correct_nation)
        }

    elif q_type == "nickname":
        team, correct_nick = random.choice(NICKNAMES)
        wrong_candidates = [n[1] for n in NICKNAMES if n[1] != correct_nick]
        opts = random.sample(wrong_candidates, 3) + [correct_nick]
        random.shuffle(opts)
        return {
            "question": f"کدام لقب مشهور متعلق به باشگاه «{team}» است؟",
            "options": opts,
            "correct_idx": opts.index(correct_nick)
        }

    elif q_type == "number":
        player_info, correct_num = random.choice(LEGENDS_NUMBERS)
        all_nums = ["3", "4", "5", "6", "7", "8", "9", "10", "11", "14", "21"]
        wrong_candidates = [n for n in all_nums if n != correct_num]
        opts = [f"شماره {n}" for n in random.sample(wrong_candidates, 3) + [correct_num]]
        random.shuffle(opts)
        return {
            "question": f"شماره پیراهن مشهور {player_info} چند بود؟",
            "options": opts,
            "correct_idx": opts.index(f"شماره {correct_num}")
        }

    elif q_type == "wc_host":
        year, correct_host = random.choice(WORLD_CUP_HOSTS)
        wrong_candidates = list({h[1] for h in WORLD_CUP_HOSTS if h[1] != correct_host})
        opts = random.sample(wrong_candidates, 3) + [correct_host]
        random.shuffle(opts)
        return {
            "question": f"میزبان مسابقات جام جهانی فوتبال در سال {year} کدام کشور بود؟",
            "options": opts,
            "correct_idx": opts.index(correct_host)
        }

    elif q_type == "wc_winner":
        year, correct_winner = random.choice(WORLD_CUP_WINNERS)
        all_champs = ["برزیل", "آلمان", "ایتالیا", "آرژانتین", "فرانسه", "اسپانیا", "انگلیس", "هلند"]
        wrong_candidates = [c for c in all_champs if c != correct_winner]
        opts = random.sample(wrong_candidates, 3) + [correct_winner]
        random.shuffle(opts)
        return {
            "question": f"کدام کشور قهرمان جام جهانی فوتبال در سال {year} شد؟",
            "options": opts,
            "correct_idx": opts.index(correct_winner)
        }

    elif q_type == "ucl_winner":
        year, correct_winner = random.choice(UCL_WINNERS)
        all_ucl = ["رئال مادرید", "بارسلونا", "بایرن مونیخ", "لیورپول", "چلسی", "منچسترسیتی", "اینتر میلان", "میلان", "یوونتوس"]
        wrong_candidates = [t for t in all_ucl if t != correct_winner]
        opts = random.sample(wrong_candidates, 3) + [correct_winner]
        random.shuffle(opts)
        return {
            "question": f"کدام تیم فاتح فینال لیگ قهرمانان اروپا (UCL) در فصل {year} شد؟",
            "options": opts,
            "correct_idx": opts.index(correct_winner)
        }

    elif q_type == "ballon_dor":
        year, correct_winner = random.choice(BALLON_DOR_WINNERS)
        all_stars = ["لیونل مسی", "کریستیانو رونالدو", "لوکا مودریچ", "کریم بنزما", "کاکا", "رونالدینیو", "زین‌الدین زیدان", "تیری آنری"]
        wrong_candidates = [s for s in all_stars if s != correct_winner]
        opts = random.sample(wrong_candidates, 3) + [correct_winner]
        random.shuffle(opts)
        return {
            "question": f"برنده جایزه توپ طلای فوتبال (Ballon d'Or) در سال {year} چه کسی بود؟",
            "options": opts,
            "correct_idx": opts.index(correct_winner)
        }

    else:
        item = random.choice(MASTER_FACTS)
        opts = item["options"][:]
        correct_text = item["correct"]
        random.shuffle(opts)
        return {
            "question": item["q"],
            "options": opts,
            "correct_idx": opts.index(correct_text)
        }

def get_random_duel_questions(count=3):
    """تولید ۳ سوال کاملاً تصادفی و غیرتکراری برای هر دوئل"""
    questions = []
    used_questions = set()
    attempts = 0
    while len(questions) < count and attempts < 30:
        attempts += 1
        q = generate_dynamic_question()
        if q["question"] not in used_questions:
            used_questions.add(q["question"])
            questions.append(q)
    return questions
