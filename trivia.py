def generate_dynamic_question():
    q_type = random.choice(["stadium", "nation", "nickname", "transfer", "number", "facts"])

    if q_type == "stadium":
        team, correct_stadium = random.choice(STADIUMS)
        wrong = [s[1] for s in STADIUMS if s[1] != correct_stadium]
        opts = random.sample(wrong, 3) + [correct_stadium]
        random.shuffle(opts)
        return {"question": f"ورزشگاه خانگی تیم «{team}» چه نام دارد؟", "options": opts, "correct_idx": opts.index(correct_stadium)}

    elif q_type == "nation":
        player, correct_nation = random.choice(NATIONS)
        wrong = list({n[1] for n in NATIONS if n[1] != correct_nation})
        opts = random.sample(wrong, 3) + [correct_nation]
        random.shuffle(opts)
        return {"question": f"«{player}» برای کدام تیم ملی بازی می‌کند؟", "options": opts, "correct_idx": opts.index(correct_nation)}

    elif q_type == "nickname":
        team, correct_nick = random.choice(NICKNAMES)
        wrong = [n[1] for n in NICKNAMES if n[1] != correct_nick]
        opts = random.sample(wrong, 3) + [correct_nick]
        random.shuffle(opts)
        return {"question": f"کدام لقب مشهور متعلق به باشگاه «{team}» است؟", "options": opts, "correct_idx": opts.index(correct_nick)}

    elif q_type == "transfer":
        p_name, src, dst = random.choice(TRANSFERS)
        all_teams = ["بارسلونا", "رئال مادرید", "منچسترسیتی", "منچستریونایتد", "پاری‌سن‌ژرمن", "چلسی", "بایرن مونیخ", "آرسنال"]
        wrong = [t for t in all_teams if t != dst]
        opts = random.sample(wrong, 3) + [dst]
        random.shuffle(opts)
        return {"question": f"«{p_name}» در انتقالی پر سر و صدا از «{src}» به کدام تیم پیوست؟", "options": opts, "correct_idx": opts.index(dst)}

    elif q_type == "number":
        player_info, correct_num = random.choice(LEGENDS_NUMBERS)
        all_nums = ["3", "4", "5", "7", "8", "9", "10", "11", "14"]
        wrong = [n for n in all_nums if n != correct_num]
        opts = [f"شماره {n}" for n in random.sample(wrong, 3) + [correct_num]]
        random.shuffle(opts)
        return {"question": f"شماره پیراهن معروف {player_info} چند بود؟", "options": opts, "correct_idx": opts.index(f"شماره {correct_num}")}

    else:
        item = random.choice(MASTER_FACTS)
        opts = item["options"][:]
        correct_text = item["correct"]
        random.shuffle(opts)
        return {"question": item["q"], "options": opts, "correct_idx": opts.index(correct_text)}

def get_random_duel_questions(count=3):
    questions = []
    used_questions = set()
    attempts = 0
    while len(questions) < count and attempts < 30:
        attempts += 1
        q = generate_dynamic_question()
        if q["question"] not in used_questions:
            used_questions.add(q["question"])
            questions.append(q)
    return questions
