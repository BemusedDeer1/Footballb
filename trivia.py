def generate_dynamic_question():
    """تولید یک سوال تصادفی فوق‌العاده با ترکیب ماتریسی داده‌ها"""
    mode = random.choice(["stadium", "nation", "transfer", "ucl_final", "ucl_venue", "ballon_dor", "hard_fact"])

    if mode == "stadium":
        item = random.choice(DATA_STADIUMS)
        team, correct_s, country = item
        wrong_candidates = [s[1] for s in DATA_STADIUMS if s[1] != correct_s]
        opts = random.sample(wrong_candidates, 3) + [correct_s]
        random.shuffle(opts)
        return {
            "question": f"ورزشگاه خانگی تیم «{team}» ({country}) چه نام دارد؟",
            "options": opts,
            "correct_idx": opts.index(correct_s)
        }

    elif mode == "nation":
        player, correct_nation = random.choice(DATA_PLAYERS_COUNTRY)
        all_nations = list({p[1] for p in DATA_PLAYERS_COUNTRY if p[1] != correct_nation})
        opts = random.sample(all_nations, 3) + [correct_nation]
        random.shuffle(opts)
        return {
            "question": f"«{player}» برای کدام تیم ملی فوتبال به میدان می‌رود؟",
            "options": opts,
            "correct_idx": opts.index(correct_nation)
        }

    elif mode == "transfer":
        item = random.choice(DATA_TRANSFERS)
        player, src, dst, fee = item
        q_sub = random.choice(["from", "to"])
        if q_sub == "from":
            wrong_candidates = list({t[1] for t in DATA_TRANSFERS if t[1] != src and t[1] != dst})
            opts = random.sample(wrong_candidates, 3) + [src]
            random.shuffle(opts)
            return {
                "question": f"«{player}» در انتقالی بزرگ با ارزش تقریبی {fee} از کدام تیم به «{dst}» پیوست؟",
                "options": opts,
                "correct_idx": opts.index(src)
            }
        else:
            wrong_candidates = list({t[2] for t in DATA_TRANSFERS if t[2] != dst})
            opts = random.sample(wrong_candidates, 3) + [dst]
            random.shuffle(opts)
            return {
                "question": f"«{player}» در انتقالی رکوردشکن با مبلغ {fee} از تیم «{src}» به چه تیمی ترانسفر شد؟",
                "options": opts,
                "correct_idx": opts.index(dst)
            }

    elif mode == "ucl_final":
        year, winner, runner_up, _ = random.choice(DATA_UCL_FINALS)
        all_teams = ["رئال مادرید", "بارسلونا", "بایرن مونیخ", "لیورپول", "چلسی", "منچسترسیتی", "اینتر میلان", "میلان", "یوونتوس", "دورتموند"]
        wrong_candidates = [t for t in all_teams if t != winner]
        opts = random.sample(wrong_candidates, 3) + [winner]
        random.shuffle(opts)
        return {
            "question": f"کدام تیم در فینال لیگ قهرمانان اروپا (UCL) فصل {year} با شکست دادن «{runner_up}» قهرمان شد؟",
            "options": opts,
            "correct_idx": opts.index(winner)
        }

    elif mode == "ucl_venue":
        year, winner, runner_up, venue = random.choice(DATA_UCL_FINALS)
        wrong_venues = list({f[3] for f in DATA_UCL_FINALS if f[3] != venue})
        opts = random.sample(wrong_venues, 3) + [venue]
        random.shuffle(opts)
        return {
            "question": f"فینال حساس لیگ قهرمانان سال {year} بین «{winner}» و «{runner_up}» در کدام استادیوم برگزار شد؟",
            "options": opts,
            "correct_idx": opts.index(venue)
        }

    elif mode == "ballon_dor":
        year, winner = random.choice(DATA_BALLON_DOR)
        all_stars = ["لیونل مسی", "کریستیانو رونالدو", "لوکا مودریچ", "کریم بنزما", "رودری", "کاکا", "رونالدینیو", "زین‌الدین زیدان", "تیری آنری", "ژاوی"]
        wrong_stars = [s for s in all_stars if s != winner]
        opts = random.sample(wrong_stars, 3) + [winner]
        random.shuffle(opts)
        return {
            "question": f"برنده معتبرترین جایزه انفرادی فوتبال، توپ طلا (Ballon d'Or) در سال {year} چه کسی بود؟",
            "options": opts,
            "correct_idx": opts.index(winner)
        }

    else:
        item = random.choice(HARD_FACTS)
        opts = item["options"][:]
        correct_text = item["correct"]
        random.shuffle(opts)
        return {
            "question": item["q"],
            "options": opts,
            "correct_idx": opts.index(correct_text)
        }

def get_random_duel_questions(count=3):
    """تولید ۳ سوال کاملاً سخت و تصادفی برای دوئل بدون تکرار"""
    questions = []
    used_questions = set()
    attempts = 0
    while len(questions) < count and attempts < 50:
        attempts += 1
        q = generate_dynamic_question()
        if q["question"] not in used_questions:
            used_questions.add(q["question"])
            questions.append(q)
    return questions
