def build_full_question_deck():
    """تولید دسته کارت فوق‌العاده حجیم و جامع برای پرسش بدون تکرار"""
    deck = []

    # ۱. فکت‌های ثابت
    for item in HARD_FACTS:
        opts = item["options"][:]
        c_text = item["correct"]
        random.shuffle(opts)
        deck.append({
            "question": item["q"],
            "options": opts,
            "correct_idx": opts.index(c_text)
        })

    # ۲. استادیوم‌ها
    for team, correct_s, country in DATA_STADIUMS:
        wrong_candidates = [s[1] for s in DATA_STADIUMS if s[1] != correct_s]
        opts = random.sample(wrong_candidates, 3) + [correct_s]
        random.shuffle(opts)
        deck.append({
            "question": f"ورزشگاه خانگی تیم «{team}» ({country}) چه نام دارد؟",
            "options": opts,
            "correct_idx": opts.index(correct_s)
        })

    # ۳. تیم ملی ستاره‌ها
    all_nations = list({p[1] for p in DATA_PLAYERS_COUNTRY})
    for player, correct_nation in DATA_PLAYERS_COUNTRY:
        wrong = [n for n in all_nations if n != correct_nation]
        opts = random.sample(wrong, 3) + [correct_nation]
        random.shuffle(opts)
        deck.append({
            "question": f"«{player}» برای کدام تیم ملی فوتبال به میدان می‌رود؟",
            "options": opts,
            "correct_idx": opts.index(correct_nation)
        })

    # ۴. نقل و انتقالات تاریخی
    all_teams_dst = list({t[2] for t in DATA_TRANSFERS})
    all_teams_src = list({t[1] for t in DATA_TRANSFERS})
    for player, src, dst, fee in DATA_TRANSFERS:
        wrong_dst = [t for t in all_teams_dst if t != dst]
        opts_dst = random.sample(wrong_dst, 3) + [dst]
        random.shuffle(opts_dst)
        deck.append({
            "question": f"«{player}» در انتقالی پر سر و صدا با مبلغ تقریبی {fee} از «{src}» به چه تیمی منتقل شد؟",
            "options": opts_dst,
            "correct_idx": opts_dst.index(dst)
        })

        wrong_src = [t for t in all_teams_src if t != src]
        opts_src = random.sample(wrong_src, 3) + [src]
        random.shuffle(opts_src)
        deck.append({
            "question": f"«{player}» قبل از پیوستن به «{dst}» در انتقالی به ارزش {fee} در کدام تیم بازی می‌کرد؟",
            "options": opts_src,
            "correct_idx": opts_src.index(src)
        })

    # ۵. توپ طلا
    all_stars = list({s[1] for s in DATA_BALLON_DOR} | {"تیری آنری", "ژاوی", "آندرس اینیستا", "مانوئل نویر", "فرانک ریبری"})
    for year, winner in DATA_BALLON_DOR:
        wrong = [s for s in all_stars if s != winner]
        opts = random.sample(wrong, 3) + [winner]
        random.shuffle(opts)
        deck.append({
            "question": f"برنده معتبرترین جایزه انفرادی فوتبال، توپ طلا (Ballon d'Or) در سال {year} چه کسی بود؟",
            "options": opts,
            "correct_idx": opts.index(winner)
        })

    # ۶. فینال‌های لیگ قهرمانان
    all_ucl_teams = list({f[1] for f in DATA_UCL_FINALS} | {f[2] for f in DATA_UCL_FINALS})
    all_venues = list({f[3] for f in DATA_UCL_FINALS})
    for year, winner, runner_up, venue in DATA_UCL_FINALS:
        wrong_teams = [t for t in all_ucl_teams if t != winner]
        opts_w = random.sample(wrong_teams, 3) + [winner]
        random.shuffle(opts_w)
        deck.append({
            "question": f"کدام تیم در فینال لیگ قهرمانان سال {year} با غلبه بر «{runner_up}» به مقام قهرمانی رسید؟",
            "options": opts_w,
            "correct_idx": opts_w.index(winner)
        })

        wrong_v = [v for v in all_venues if v != venue]
        opts_v = random.sample(wrong_v, 3) + [venue]
        random.shuffle(opts_v)
        deck.append({
            "question": f"دیدار فینال لیگ قهرمانان اروپا در سال {year} بین «{winner}» و «{runner_up}» در کدام استادیوم برگزار شد؟",
            "options": opts_v,
            "correct_idx": opts_v.index(venue)
        })

    # ۷. فینال‌های جام جهانی
    all_wc_teams = ["برزیل", "آلمان", "ایتالیا", "آرژانتین", "فرانسه", "اسپانیا", "هلند", "کرواسی"]
    for year, winner, runner_up, venue in DATA_WC_FINALS:
        wrong_wc = [t for t in all_wc_teams if t != winner]
        opts_wc = random.sample(wrong_wc, 3) + [winner]
        random.shuffle(opts_wc)
        deck.append({
            "question": f"در فینال خاطره‌انگیز جام جهانی {year} کدام کشور با شکست «{runner_up}» قهرمان جهان شد؟",
            "options": opts_wc,
            "correct_idx": opts_wc.index(winner)
        })

    # ۸. سال تأسیس باشگاه‌ها
    all_years = ["۱۸۷۸", "۱۸۸۰", "۱۸۸۶", "۱۸۹۲", "۱۸۹۷", "۱۸۹۹", "۱۹۰۰", "۱۹۰۲", "۱۹۰۳", "۱۹۰۵", "۱۹۰۸", "۱۹۰۹", "۱۹۷۰"]
    for club, yr in DATA_CLUB_FOUNDED:
        wrong_yr = [y for y in all_years if y != yr]
        opts_yr = random.sample(wrong_yr, 3) + [yr]
        random.shuffle(opts_yr)
        deck.append({
            "question": f"باشگاه تاریخی و پرطرفدار «{club}» در چه سالی تأسیس شد؟",
            "options": opts_yr,
            "correct_idx": opts_yr.index(yr)
        })

    # ۹. آقای گل‌های لیگ قهرمانان
    all_scorers = [s[1] for s in DATA_UCL_TOP_SCORERS]
    for season, scorer in DATA_UCL_TOP_SCORERS:
        wrong_sc = [s for s in all_scorers if s != scorer]
        opts_sc = random.sample(wrong_sc, 3) + [scorer]
        random.shuffle(opts_sc)
        deck.append({
            "question": f"عنوان آقای گل رقابت‌های لیگ قهرمانان اروپا در فصل {season} به چه کسی رسید؟",
            "options": opts_sc,
            "correct_idx": opts_sc.index(scorer)
        })

    random.shuffle(deck)
    return deck

QUESTION_DECK = []

def get_random_duel_questions(count=3):
    """برداشت سوالات دوئل به شیوه نوبتی بدون تکرار از روی دسته بزرگ سوالات"""
    global QUESTION_DECK
    if len(QUESTION_DECK) < count:
        QUESTION_DECK = build_full_question_deck()

    selected = []
    for _ in range(count):
        selected.append(QUESTION_DECK.pop())
    return selected
