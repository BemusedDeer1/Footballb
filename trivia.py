def get_random_duel_questions(count=3):
    """تولید و شافل سوالات برای هر دوئل به شکل کاملاً داینامیک"""
    selected = random.sample(TRIVIA_TEMPLATES, min(count, len(TRIVIA_TEMPLATES)))
    questions = []
    for item in selected:
        opts = item["options"][:]
        correct_text = opts[item["correct"]]
        random.shuffle(opts)
        new_correct_idx = opts.index(correct_text)
        questions.append({
            "question": item["q"],
            "options": opts,
            "correct_idx": new_correct_idx
        })
    return questions
